#!/usr/bin/env node
// Generates the local, git-ignored root .env with random secrets (Docker Compose and the API).
// Refuses to write a file Git would track, writes with owner-only permissions (0600) and prints
// setting names only, never values.
//
//   npm run env:init                      create .env (refuses if it exists)
//   npm run env:init -- --add-missing     append settings an existing .env lacks (new secrets are
//                                         random); existing values are never changed or shown
import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { appendFileSync, chmodSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, '.env');
const addMissing = process.argv.includes('--add-missing');

try {
  execFileSync('git', ['check-ignore', '-q', '.env'], { cwd: root });
} catch {
  console.error('.env is not ignored by Git; refusing to write secrets into it.');
  process.exit(1);
}

const secret = () => randomBytes(32).toString('hex'); // 64 hex characters
const url = (user, password, name) => `postgres://${user}:${password}@127.0.0.1:5433/${name}`;

/** Settings added after the first release of this script, in the order they are appended. */
const LATER_SETTINGS = () => [
  ['RESET_CODE_PEPPER', secret()],
  ['SMTP_HOST', '127.0.0.1'],
  ['SMTP_PORT', '1026'],
  ['MAIL_FROM', 'no-reply@hospitalos.invalid'],
  // Development only: lets the Expo web build call the local API.
  ['CORS_ORIGINS', 'http://localhost:8081'],
];

if (addMissing) {
  if (!existsSync(target)) {
    console.error('.env does not exist; run npm run env:init first.');
    process.exit(1);
  }
  const present = new Set(
    readFileSync(target, 'utf8')
      .split('\n')
      .map((line) => line.split('=')[0]?.trim())
      .filter(Boolean),
  );
  const missing = LATER_SETTINGS().filter(([name]) => !present.has(name));
  if (missing.length === 0) {
    console.log('.env already has every setting.');
    process.exit(0);
  }
  appendFileSync(target, `\n${missing.map(([name, value]) => `${name}=${value}`).join('\n')}\n`);
  chmodSync(target, 0o600);
  console.log(`added to .env: ${missing.map(([name]) => name).join(', ')}`);
  process.exit(0);
}

if (existsSync(target)) {
  console.error(
    '.env already exists; not overwriting it. Use --add-missing to add new settings, or inspect and remove it.',
  );
  process.exit(1);
}

const ownerPassword = secret();
const appPassword = secret();

const lines = [
  '# Generated by scripts/env-init.mjs. Git-ignored. Never commit, print or share.',
  'POSTGRES_USER=hospitalos_mobile_admin',
  `POSTGRES_PASSWORD=${secret()}`,
  `HOS_OWNER_PASSWORD=${ownerPassword}`,
  `HOS_APP_PASSWORD=${appPassword}`,
  'NODE_ENV=development',
  'HOST=127.0.0.1',
  'PORT=4000',
  'LOG_LEVEL=info',
  'RATE_LIMIT_WINDOW_MS=60000',
  'RATE_LIMIT_MAX=300',
  `DATABASE_URL=${url('hos_app', appPassword, 'hospitalos_dev')}`,
  'DATABASE_ALLOWED_NAMES=hospitalos_dev',
  `MIGRATION_DATABASE_URL=${url('hos_owner', ownerPassword, 'hospitalos_dev')}`,
  `TEST_DATABASE_URL=${url('hos_app', appPassword, 'hospitalos_test')}`,
  `TEST_MIGRATION_DATABASE_URL=${url('hos_owner', ownerPassword, 'hospitalos_test')}`,
  ...LATER_SETTINGS().map(([name, value]) => `${name}=${value}`),
  '',
];

writeFileSync(target, lines.join('\n'), { mode: 0o600, flag: 'wx' });
console.log('wrote .env (mode 600)');
